/* =========================================================
   EXPORT / RUNTIME LOGIC FOR PRODUCT DETAIL PAGE
========================================================= */

if (typeof window !== "undefined") {
    // If on product.html page, populate the page content
    const params = new URLSearchParams(window.location.search);
    const productKey = params.get("product");

    if (productKey && kulfis[productKey]) {
        const product = kulfis[productKey];

        const imgEl = document.getElementById("productImage");
        if (imgEl) {
            imgEl.src = product.image;
            imgEl.alt = product.name;
        }

        const numEl = document.getElementById("productNumber");
        if (numEl) numEl.textContent = product.number;

        const nameEl = document.getElementById("productName");
        if (nameEl) nameEl.textContent = product.name;

        const labelEl = document.querySelector(".product-label");
        if (labelEl) labelEl.textContent = (product.category || "AUTHENTIC INDIAN KULFI").toUpperCase();

        const descEl = document.getElementById("productDescription");
        if (descEl) descEl.textContent = product.description;

        const priceContainer = document.querySelector(".product-price");
        const priceEl = document.getElementById("productPrice");
        if (priceEl && priceContainer) {
            if (product.price) {
                priceEl.textContent = product.price;
                priceContainer.style.display = "flex";
            } else {
                priceContainer.style.display = "none";
            }
        }

        const ingEl = document.getElementById("productIngredients");
        if (ingEl) ingEl.textContent = product.ingredients;

        const specEl = document.getElementById("productSpeciality");
        if (specEl) specEl.textContent = product.speciality;

        document.title = product.name + " | Kulfi Corner";
    }

    // Mobile menu toggle for product.html
    const menuToggle = document.getElementById("menuToggle");
    const navMenu = document.querySelector(".nav-menu");
    if (menuToggle && navMenu) {
        menuToggle.addEventListener("click", () => {
            navMenu.classList.toggle("show");
        });
    }
}
